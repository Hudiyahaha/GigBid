"""LLM-judge calibration (B4). Step 1 scores 30 proposals with the judge and writes a CSV for HUMAN labelling.
Step 2 (after you fill `human_score` 1-5) computes Cohen's kappa (quadratic-weighted and on pass/fail >= 4).

    python -m evals.runners.judge_calibration score      # needs evals/results/gigsim_outcomes.json (letters)
    python -m evals.runners.judge_calibration kappa      # after labelling evals/results/judge_labels.csv
Human labels are never generated by code.
"""

from __future__ import annotations

import asyncio
import csv
import json
import sys

from evals.common import RESULTS, load_jobs, write_result

CSV = RESULTS / "judge_labels.csv"


async def score() -> None:
    from agent import llm
    llm.start_usage()
    out = json.loads((RESULTS / "gigsim_outcomes.json").read_text(encoding="utf-8"))
    jobs = load_jobs()
    items = []
    for r in out["rows"]:
        for strat, key in (("evidence_first", "letter_a"), ("question_first", "letter_b")):
            if r.get(key):
                items.append((r["job_id"], strat, r[key]))
    items = items[:30]
    rows = []
    for jid, strat, letter in items:
        res, meta = await llm.call_json("judge", "judge", {"job": jobs[jid]["description"][:1500], "proposal": letter}, None,
                                        heuristic=lambda: {"score": None, "reason": "judge unavailable"}, max_tokens=300)
        rows.append({"job_id": jid, "strategy": strat, "judge_score": res.get("score"), "judge_reason": res.get("reason", "")[:200],
                     "human_score": "", "proposal": letter})
        print(jid, strat, res.get("score"), flush=True)
    with open(CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {CSV}: fill the human_score column (1-5) yourself, then run `kappa`")


def cohen(a: list[int], b: list[int], weighted: bool) -> float:
    cats = sorted(set(a) | set(b))
    k = len(cats)
    idx = {c: i for i, c in enumerate(cats)}
    n = len(a)
    o = [[0.0] * k for _ in range(k)]
    for x, y in zip(a, b, strict=True):
        o[idx[x]][idx[y]] += 1 / n
    pa = [sum(r) for r in o]
    pb = [sum(o[i][j] for i in range(k)) for j in range(k)]

    def w(i, j):
        return ((i - j) ** 2 / (k - 1) ** 2 if k > 1 else 0) if weighted else (0 if i == j else 1)
    obs = sum(w(i, j) * o[i][j] for i in range(k) for j in range(k))
    exp = sum(w(i, j) * pa[i] * pb[j] for i in range(k) for j in range(k))
    return round(1 - obs / exp, 4) if exp else 1.0


def kappa() -> None:
    rows = [r for r in csv.DictReader(open(CSV, encoding="utf-8")) if r["human_score"].strip() and r["judge_score"]]
    j = [int(float(r["judge_score"])) for r in rows]
    h = [int(float(r["human_score"])) for r in rows]
    disagree = [r for r in rows if abs(int(float(r["judge_score"])) - int(float(r["human_score"]))) >= 2]
    write_result("judge_calibration", {"n": len(rows), "kappa_quadratic": cohen(j, h, True),
                                       "kappa_pass_fail": cohen([x >= 4 for x in j], [x >= 4 for x in h], False),
                                       "disagreements": [{k: r[k] for k in ("job_id", "strategy", "judge_score", "human_score", "judge_reason")}
                                                         for r in disagree]})


if __name__ == "__main__":
    asyncio.run(score()) if sys.argv[1:] == ["score"] else kappa()
